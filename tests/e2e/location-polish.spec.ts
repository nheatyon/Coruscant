import { test, expect } from '@playwright/test';
import type { RequestProjection } from '../../shared/contracts.js';
import { chooseDemonstrationCatalog, showDiscoveryList } from './helpers.js';

test.setTimeout(120_000);

test('an applied single place keeps usable recovery controls while a numeric correction is staged or canceled @r022', async ({ page }) => {
  await page.goto('/'); await chooseDemonstrationCatalog(page);
  const question = page.getByLabel('Search satellites and services', { exact: true });
  if (!await question.isVisible()) await page.getByRole('button', { name: 'Discover', exact: true }).click();
  await question.fill('Visible imagery of Dublin.');
  await page.getByRole('button', { name: 'Explore matches & find place', exact: true }).click();
  await page.getByRole('button', { name: 'Apply proposed location', exact: true }).click();
  await page.getByRole('button', { name: 'Earth observation', exact: true }).click(); await showDiscoveryList(page);
  await page.getByRole('button', { name: /Review this mission/ }).click();
  const brief = page.getByRole('dialog', { name: 'Your request', exact: true });
  const lookup = brief.getByRole('region', { name: 'Place lookup and proposed area', exact: true });
  await expect(lookup.locator('summary').filter({ hasText: 'Change location' })).toBeVisible();
  await brief.getByLabel('Centre latitude', { exact: true }).fill('53.35');
  await expect(lookup).toContainText('UNAPPLIED AREA PROPOSAL');
  await expect(lookup.locator('summary').filter({ hasText: 'Change location' })).toHaveCount(0);
  await expect(lookup.getByRole('button', { name: 'Apply proposed location', exact: true })).toBeVisible();
  await lookup.getByRole('button', { name: 'Cancel proposal', exact: true }).click();
  const change = lookup.locator('summary').filter({ hasText: 'Change location' });
  await change.click();
  await expect(lookup.getByRole('button', { name: 'Preview returned location', exact: true })).toBeVisible();
  await expect(brief.getByLabel('Centre latitude', { exact: true })).toHaveValue('53.3498');
});

test('applied lookup folds alternatives; an explicit numeric adjustment keeps original and applied source lineage @r022', async ({ page }) => {
  await page.addInitScript(() => { const original = HTMLCanvasElement.prototype.getContext; HTMLCanvasElement.prototype.getContext = function(this: HTMLCanvasElement, kind, ...args) { return kind === 'webgl2' ? null : Reflect.apply(original, this, [kind, ...args]); } as typeof original; });
  await page.goto('/'); await chooseDemonstrationCatalog(page);
  const question = page.getByLabel('Search satellites and services', { exact: true });
  if (!await question.isVisible()) await page.getByRole('button', { name: 'Discover', exact: true }).click();
  await question.fill('Visible imagery of Springfield.');
  await page.getByRole('button', { name: 'Explore matches & find place', exact: true }).click();
  await page.getByRole('button', { name: /Springfield North — generated/ }).click();
  await page.getByRole('button', { name: 'Apply proposed location', exact: true }).click();
  const lookup = page.getByRole('region', { name: 'Place lookup and proposed area', exact: true }).first();
  await expect(lookup).toContainText('Selected source: Springfield North');
  const change = lookup.locator('summary').filter({ hasText: 'Change location' });
  await expect(change).toBeVisible();
  const south = lookup.getByRole('button', { name: /Springfield South — generated/ });
  await expect(south).toBeHidden(); await change.focus(); await change.press('Enter'); await expect(south).toBeVisible();
  await change.press('Enter'); await expect(south).toBeHidden();
  await page.getByRole('button', { name: 'Earth observation', exact: true }).click(); await showDiscoveryList(page);
  await page.getByRole('button', { name: /Review this mission/ }).click();
  const brief = page.getByRole('dialog', { name: 'Your request', exact: true });
  const original = { latitude: Number(await brief.getByLabel('Centre latitude', { exact: true }).inputValue()), longitude: Number(await brief.getByLabel('Centre longitude', { exact: true }).inputValue()) };
  const adjusted = { latitude: original.latitude + .001, longitude: original.longitude, radiusKm: 30.123456789 };
  await brief.getByLabel('Centre latitude', { exact: true }).fill(String(adjusted.latitude));
  await brief.getByLabel('Radius (km)', { exact: true }).fill(String(adjusted.radiusKm));
  await brief.getByRole('button', { name: 'Use these coordinates', exact: true }).click();
  const context = brief.getByRole('region', { name: 'Current area and place names', exact: true });
  await expect(context).toContainText('Adjusted from Springfield North');
  await expect(context).toContainText(`Original returned center ${original.latitude.toFixed(5)}°, ${original.longitude.toFixed(5)}°`);
  await expect(context).toContainText('30.123 km radius');
  await expect(brief.getByLabel('Radius (km)', { exact: true })).toHaveValue(String(adjusted.radiusKm));
  await brief.getByRole('checkbox', { name: 'I chose this target and checked the area size.', exact: true }).check();
  await brief.getByRole('button', { name: 'Review request', exact: true }).click();
  await page.getByRole('link', { name: 'Open customer workspace', exact: true }).click();
  await page.getByRole('combobox', { name: 'Demonstration customer', exact: true }).selectOption('a-owner');
  await page.getByRole('button', { name: 'Continue to workspace', exact: true }).click();
  await page.getByRole('button', { name: 'Review request in this workspace', exact: true }).click();
  await page.getByRole('checkbox', { name: 'I confirm this planning brief and destination. This does not request staff review.', exact: true }).check();
  await page.getByRole('button', { name: 'Save planning request', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Request saved', exact: true })).toBeVisible();
  await page.getByRole('link', { name: 'Open request in Demo Estuary Research', exact: true }).click();
  const id = new URL(page.url()).pathname.split('/').at(-1)!;
  const saved = await (await page.request.get(`/api/customer/org-a/requests/${id}`)).json() as RequestProjection;
  expect(saved.status).toBe('Planning'); expect(saved.history.filter(event => event.type === 'Planning saved')).toHaveLength(1);
  expect(saved.brief.area).toMatchObject(adjusted);
  expect(saved.brief.areaSource).toMatchObject({ sourceCenter: original, appliedCenter: { latitude: adjusted.latitude, longitude: adjusted.longitude }, appliedRadiusKm: adjusted.radiusKm, adjusted: true });
  await page.reload();
  await page.getByText('Planning brief and evidence · Revision 1', { exact: true }).click();
  await page.getByText('Applied place source and circle', { exact: true }).click();
  await expect(page.getByText('deliberately adjusted', { exact: false }).first()).toBeVisible();
});
